# Car Recommendation Models
# ─────────────────────────────────────────────

class CarSpec(BaseModel):
    car_name: str = Field(description="Full name of the car")
    brand: str = Field(description="Car manufacturer/brand")
    price_range: str = Field(description="Price range in INR (e.g., ₹8L - ₹12L)")
    fuel_types: list[str] = Field(description="Supported fuel types (e.g. Petrol, Diesel, EV, CNG, Hybrid)")
    mileage_kmpl: float = Field(description="Mileage in km per litre or km per charge")
    engine_cc: Optional[int] = Field(default=None, description="Engine displacement in CC")
    seating_capacity: int = Field(description="Number of seats")
    transmissions: list[str] = Field(description="Available transmission options (e.g. Manual, Automatic, CVT, DCT)")
    pros: list[str] = Field(description="Key advantages of this car")
    cons: list[str] = Field(description="Key disadvantages of this car")
    match_score: float = Field(ge=0, le=100, description="How well it matches user requirements (0-100)")
    segment: str = Field(description="Car segment e.g. Hatchback, Sedan, SUV, MUV")


class CarRecommendationResponse(BaseModel):
    recommendations: list[CarSpec] = Field(description="List of recommended cars (max 3)")
    summary: str = Field(description="Brief summary of recommendations")
    top_pick: str = Field(description="Name of the best match car")
    buying_tips: list[str] = Field(description="Tips for buying the recommended car")


