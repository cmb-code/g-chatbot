IntentType = Literal["recommend", "diagnostic", "service", "emi", "general"]
SortByOption = Literal["price_asc", "price_desc", "mileage_desc", "seating_desc", "relevance"]

class FuzzyCarFilter(BaseModel):
    """
    A set of filter parameters with fuzzy tolerances.
    The fuzzy query executor uses these to do soft matching
    instead of exact SQL equality / range constraints.
    """
    # Budget — fuzzy: ±20% of stated budget
    budget_lakh_min: Optional[float] = Field(
        default=None,
        description="Minimum price in lakhs (fuzzy lower bound)"
    )
    budget_lakh_max: Optional[float] = Field(
        default=None,
        description="Maximum price in lakhs (fuzzy upper bound, with tolerance)"
    )
    budget_tolerance_pct: float = Field(
        default=0.20,
        ge=0.0, le=1.0,
        description="How much above budget to still consider (0.20 = 20% stretch)"
    )

    # Fuel type — fuzzy: 'ev' → 'Electric', 'petrol'→'Petrol', etc.
    fuel_type: Optional[str] = Field(
        default=None,
        description="Desired fuel type (raw, will be fuzzy-matched to DB values)"
    )

    # Segment — fuzzy: 'family car' → SUV/MUV, 'small car' → Hatchback
    segment: Optional[str] = Field(
        default=None,
        description="Car segment keyword (fuzzy-matched)"
    )

    # Seating — fuzzy: 5-seater → [4,5,6], 7-seater → [6,7,8]
    min_seating: Optional[int] = Field(
        default=None,
        description="Minimum number of seats required"
    )

    # Transmission preference
    transmission: Optional[str] = Field(
        default=None,
        description="Preferred transmission: Manual, Automatic, CVT, DCT"
    )

    # Car name — fuzzy string match for typos (e.g. 'cretta' → 'Creta')
    car_name_query: Optional[str] = Field(
        default=None,
        description="Specific car name to look up (fuzzy typo-tolerant match)"
    )

    # Features (keywords to match against features array)
    feature_keywords: list[str] = Field(
        default_factory=list,
        description="Feature keywords to match (e.g. sunroof, ADAS, 360 camera)"
    )

    # Issue keyword for diagnostic fuzzy search
    issue_keyword: Optional[str] = Field(
        default=None,
        description="Symptom or issue keyword for fuzzy common_issues lookup"
    )

    # Brand preference
    brand: Optional[str] = Field(
        default=None,
        description="Preferred brand (Maruti, Hyundai, Tata, etc.)"
    )


class QueryPlan(BaseModel):
    """
    Full dynamic query plan generated by the Query Agent from raw user prompt.

    Instead of agents calling hardcoded tool functions, the Query Agent
    analyses the user message and produces this structured plan.
    The fuzzy query executor then executes it against the DB.
    """
    intent: IntentType = Field(
        description="The resolved intent for this query"
    )
    filters: FuzzyCarFilter = Field(
        default_factory=FuzzyCarFilter,
        description="Structured filter parameters for DB query"
    )
    sort_by: SortByOption = "relevance"
    max_results: int = Field(
        default=5,
        ge=1, le=20,
        description="Maximum number of DB results to fetch for context"
    )
    reasoning: str = Field(
        default="",
        description="Why the Query Agent chose these parameters (for logging/debug)"
    )
    # EMI-specific fields
    emi_price_lakh: Optional[float] = Field(
        default=None,
        description="Car price in lakhs for EMI calculation"
    )
    emi_interest_rate: Optional[float] = Field(
        default=None,
        description="Annual interest rate % for EMI"
    )
    emi_tenure_years: Optional[int] = Field(
        default=None,
        description="Loan tenure in years"
    )


