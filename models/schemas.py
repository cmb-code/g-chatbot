# Service & Maintenance Models
# ─────────────────────────────────────────────

class ServiceItem(BaseModel):
    item_name: str = Field(description="Name of service item e.g. Engine Oil, Air Filter")
    interval_km: int = Field(description="Service interval in km")
    last_done_km: Optional[int] = Field(default=None, description="Odometer reading when last done")
    due_at_km: Optional[int] = Field(default=None, description="Due at this odometer reading")
    status: Literal["OK", "Due Soon", "Overdue", "Unknown"] = Field(description="Current status")
    estimated_cost: str = Field(description="Estimated cost in INR")


class ServiceScheduleResponse(BaseModel):
    car_name: str = Field(description="Name of the car")
    current_mileage: int = Field(description="Current odometer reading")
    service_items: list[ServiceItem] = Field(description="List of service items and their status")
    next_service_due: str = Field(description="When is the next major service due")
    total_estimated_cost: str = Field(description="Total estimated cost for all overdue services")
    important_notes: list[str] = Field(description="Important notes for the car owner")


