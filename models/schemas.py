# Diagnostic Models
# ─────────────────────────────────────────────

class DiagnosticReport(BaseModel):
    symptom_described: str = Field(description="The symptom as described by user")
    possible_causes: list[str] = Field(description="List of possible causes for the symptom")
    most_likely_cause: str = Field(description="The most probable cause")
    severity: Literal["Low", "Medium", "High", "Critical"] = Field(description="Severity level of the issue")
    urgency: str = Field(description="How urgently should this be addressed e.g. Immediately, Within a week")
    estimated_repair_cost: str = Field(description="Estimated cost range for repair in INR")
    can_drive: bool = Field(description="Whether it is safe to drive the car currently")
    diy_possible: bool = Field(description="Whether the user can fix it themselves")
    diy_steps: Optional[list[str]] = Field(default=None, description="Steps if DIY is possible")
    workshop_recommendation: str = Field(description="What to tell the mechanic at the workshop")
    parts_that_may_need_replacement: list[str] = Field(description="Parts that may need to be replaced")


