"""
Pydantic Models for AutoBot - Structured Data Schemas
"""
from __future__ import annotations

from pydantic import BaseModel, Field
from typing import Literal, Optional, Any


# ─────────────────────────────────────────────
# Routing / Orchestrator Models
# ─────────────────────────────────────────────

class RoutingDecision(BaseModel):
    """
    Pydantic AI output type for the Master Orchestrator multi-intent routing agent.
    Replaces manual JSON parsing to support single and parallel multi-intent routing.
    """
    intents: list[str] = Field(
        default_factory=lambda: ["recommend_cars"],
        description=(
            "List of one or more tool/intent names to route to. "
            "Possible items: recommend_cars, diagnose_vehicle, get_service_schedule, calculate_emi, answer_general"
        )
    )
    reason: str = Field(
        default="",
        description="Brief explanation of why these tools were selected"
    )


class MultiIntentResult(BaseModel):
    """Container aggregating structured output results from parallel sub-agents."""
    intents: list[str] = Field(description="List of executed intents")
    results: dict[str, Any] = Field(description="Map of intent -> Pydantic response object")


# ─────────────────────────────────────────────
# Query Agent Models
# ─────────────────────────────────────────────

class ExtractedEntities(BaseModel):
    """Entities extracted from the user message by the Query Agent LLM."""
    budget_lakh: Optional[float] = Field(default=None, description="Budget in lakhs")
    fuel_type: Optional[str] = Field(default=None, description="Fuel type preference")
    segment: Optional[str] = Field(default=None, description="Car segment preference")
    min_seating: Optional[int] = Field(default=None, description="Minimum seat count")
    car_name: Optional[str] = Field(default=None, description="Specific car name")
    issue_keyword: Optional[str] = Field(default=None, description="Diagnostic issue keyword")
    price_lakh: Optional[float] = Field(default=None, description="Car price in lakhs (for EMI)")
    interest_rate: Optional[float] = Field(default=None, description="Loan interest rate %")
    tenure_years: Optional[int] = Field(default=None, description="Loan tenure in years")


class ToolCall(BaseModel):
    """A single DB tool call generated by the Query Agent LLM."""
    tool: str = Field(description="Tool name to invoke")
    args: dict[str, Any] = Field(default_factory=dict, description="Arguments to pass to the tool")


class LLMToolPlan(BaseModel):
    """
    Pydantic AI output type for the Query Agent.
    Replaces the manual JSON parsing of the raw genai.Client DB tool plan call.
    """
    tools_to_run: list[ToolCall] = Field(
        default_factory=list,
        description="List of DB tools to invoke with their arguments"
    )
    extracted_entities: ExtractedEntities = Field(
        default_factory=ExtractedEntities,
        description="Key entities extracted from the user message"
    )
    reasoning: str = Field(
        default="",
        description="Why the Query Agent chose these tools and parameters"
    )



